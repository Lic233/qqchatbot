@dataclass(frozen=True)
class Item:
    name: str
    version: str
    type: str
    tags: tuple[str, ...]
    world: str
    note: str = ""
    aliases: tuple[str, ...] = field(default_factory=tuple)
    # 这个物品有 16 种颜色（羊毛 / 陶瓦……），别名里已经带上「红色羊毛」这类写法
    colored: bool = False

    @property
    def chars(self) -> int:
        return len(self.name)


def _item(name: str, version: str, type_: str, tags: str, world: str,
          note: str = "", *aliases: str, colors: bool = False) -> Item:
    """一条题库：tags 用空格分隔（「金属 战斗 稀有」）。"""
    tag_tuple = tuple(tags.split())
    alias_tuple = tuple(aliases)
    if colors:
        alias_tuple = alias_tuple + tuple(f"{color}{name}" for color in COLORS)
    return Item(name=name, version=version, type=type_, tags=tag_tuple,
                world=world, note=note, aliases=alias_tuple, colored=colors)


def _block(name: str, version: str, tags: str, world: str,
           note: str = "", *aliases: str, colors: bool = False) -> Item:
    return _item(name, version, "方块", tags, world, note, *aliases, colors=colors)


